// Helper function (add once to course definition file)
export function parseCoords(spec) {
  const layout = {};
  for (const [type, coords] of Object.entries(spec)) {
    if (typeof coords === 'string') {
      coords.trim().split(/\s+/).forEach(c => { if (c) layout[c] = type; });
    }
  }
  return layout;
}

